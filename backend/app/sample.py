"""Fictional document used by the UI and integration tests."""
from io import BytesIO
from reportlab.lib.colors import HexColor
from reportlab.pdfgen import canvas


def make_sample() -> bytes:
    output = BytesIO()
    doc = canvas.Canvas(output, pagesize=(612, 792))
    doc.setTitle("Sample services agreement - test data only")
    ink, muted, accent = map(HexColor, ("#242c2a", "#707874", "#c36a4a"))

    def base(page):
        doc.setFillColor(accent)
        doc.rect(48, 735, 24, 4, fill=1, stroke=0)
        doc.setFillColor(ink)
        doc.setFont("Helvetica-Bold", 10)
        doc.drawString(82, 733, "NORTHSTAR STUDIO")
        doc.setFillColor(muted)
        doc.setFont("Helvetica", 8)
        doc.drawRightString(564, 733, "SAMPLE / TEST DATA ONLY")
        doc.setStrokeColor(HexColor("#dce1dd"))
        doc.line(48, 56, 564, 56)
        doc.setFont("Helvetica", 8)
        doc.drawString(48, 40, "Fictional document for testing agreement preparation. Not for business use.")
        doc.drawRightString(564, 40, f"{page} / 2")

    def paragraph(y, title, lines):
        doc.setFillColor(ink)
        doc.setFont("Helvetica-Bold", 11)
        doc.drawString(48, y, title)
        doc.setFont("Helvetica", 10)
        for index, line in enumerate(lines):
            doc.drawString(48, y - 23 - index * 17, line)

    base(1)
    doc.setFillColor(ink)
    doc.setFont("Times-Roman", 31)
    doc.drawString(48, 670, "Services agreement")
    doc.setFillColor(muted)
    doc.setFont("Helvetica", 10)
    doc.drawString(48, 643, "Prepared for Example Client Company | Reference DEMO-001")
    paragraph(590, "01  The parties", ["This sample agreement is between Northstar Studio (the Provider) and", "Example Client Company (the Client). All names and details are fictional."])
    paragraph(500, "02  Scope of work", ["The Provider will create a sample website concept for the Client. The work", "includes an initial concept, a review meeting, and one round of revisions.", "Any additional work will be discussed and agreed separately."])
    paragraph(390, "03  Timing and communication", ["Work starts after both parties confirm the project details and the Client signs", "this agreement. The parties will agree on a schedule before work begins."])
    paragraph(300, "04  Fees", ["The demonstration project fee is USD 1,000. This is fictional test data.", "No payment is requested or processed by this sample agreement."])
    doc.setFillColor(HexColor("#f4f1e9"))
    doc.roundRect(48, 127, 516, 83, 7, fill=1, stroke=0)
    doc.setFillColor(ink)
    doc.setFont("Helvetica-Bold", 10)
    doc.drawString(65, 185, "Next: acceptance and signature")
    doc.setFont("Helvetica", 10)
    doc.drawString(65, 164, "The signature area is on page 2. Use the editor to place a signature box.")
    doc.showPage()
    base(2)
    doc.setFillColor(ink)
    doc.setFont("Times-Roman", 31)
    doc.drawString(48, 670, "Acceptance")
    paragraph(612, "05  Review and changes", ["The Client will review the work and share feedback within the agreed schedule.", "Changes to scope or delivery dates require agreement by both parties."])
    paragraph(520, "06  Agreement", ["By signing below, the Client acknowledges the contents of this sample.", "This document is provided solely to test the agreement preparation workflow."])
    doc.setFont("Helvetica-Bold", 11)
    doc.drawString(48, 408, "For the Client")
    doc.setFont("Helvetica", 10)
    doc.drawString(48, 380, "Example Client Company")
    doc.setStrokeColor(HexColor("#aeb6b0"))
    doc.line(48, 265, 340, 265)
    doc.line(390, 265, 564, 265)
    doc.setFillColor(muted)
    doc.setFont("Helvetica", 9)
    doc.drawString(48, 248, "Client signature")
    doc.drawString(390, 248, "Date")
    doc.setFillColor(HexColor("#f4f1e9"))
    doc.roundRect(48, 115, 516, 76, 7, fill=1, stroke=0)
    doc.setFillColor(ink)
    doc.setFont("Helvetica-Bold", 10)
    doc.drawString(65, 166, "Try it in the editor")
    doc.setFont("Helvetica", 10)
    doc.drawString(65, 145, "Draw a box above the signature line, adjust its size, and save your template.")
    doc.save()
    return output.getvalue()
